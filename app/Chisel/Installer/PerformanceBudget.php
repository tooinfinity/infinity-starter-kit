<?php

declare(strict_types=1);

namespace App\Chisel\Installer;

use App\Models\User;
use Illuminate\Contracts\Console\Kernel;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use InvalidArgumentException;
use RuntimeException;

/**
 * Authoritative lightweight performance budgets and deterministic verification
 * for canonical requests and frontend production bundles.
 */
final readonly class PerformanceBudget
{
    public const int SCHEMA_VERSION = 1;

    public const string REQUEST_WELCOME = 'GET /';

    public const string REQUEST_LOGIN = 'GET /login';

    public const string REQUEST_DASHBOARD = 'GET /dashboard';

    /**
     * @var list<string>
     */
    public const array CANONICAL_REQUESTS = [
        self::REQUEST_WELCOME,
        self::REQUEST_LOGIN,
        self::REQUEST_DASHBOARD,
    ];

    public const string METRIC_ENTRY_JS = 'entry_js';

    public const string METRIC_ENTRY_CSS = 'entry_css';

    public const string METRIC_TOTAL_JS = 'total_js';

    public const string METRIC_TOTAL_CSS = 'total_css';

    /**
     * @var list<string>
     */
    public const array BUNDLE_METRICS = [
        self::METRIC_ENTRY_JS,
        self::METRIC_ENTRY_CSS,
        self::METRIC_TOTAL_JS,
        self::METRIC_TOTAL_CSS,
    ];

    /**
     * Canonical query count budgets per profile.
     *
     * Minimal profile:
     * - No Settings module, no RBAC, no Notifications.
     * - GET /: 0 queries (pure static Inertia welcome view)
     * - GET /login: 0 queries (pure Fortify guest view)
     * - GET /dashboard: 0 queries (auth session resolution, no middleware or prop queries)
     *
     * Default / Standard profile:
     * - Includes Settings, RBAC (roles + permissions), User Management, Notifications.
     * - GET /: max 1 query (uncached settings query by HandleSettings middleware)
     * - GET /login: max 1 query (uncached settings query by HandleSettings middleware)
     * - GET /dashboard: max 4 queries (settings + permissions + roles + unread notifications)
     *
     * Full profile:
     * - Includes all optional modules.
     * - Same canonical request overhead as default.
     *
     * @var array<string, array<string, int>>
     */
    private const array QUERY_BUDGETS = [
        Profile::MINIMAL => [
            self::REQUEST_WELCOME => 0,
            self::REQUEST_LOGIN => 0,
            self::REQUEST_DASHBOARD => 0,
        ],
        Profile::STANDARD => [
            self::REQUEST_WELCOME => 1,
            self::REQUEST_LOGIN => 1,
            self::REQUEST_DASHBOARD => 4,
        ],
        Profile::FULL => [
            self::REQUEST_WELCOME => 1,
            self::REQUEST_LOGIN => 1,
            self::REQUEST_DASHBOARD => 4,
        ],
    ];

    /**
     * Frontend production bundle size budgets in bytes.
     *
     * Hard byte ceilings for production assets generated by Vite+ / Rolldown build.
     * Baselines measured against current production builds with comfortable headroom
     * to absorb minor layout additions while catching runaway regressions (e.g. bundling
     * unpruned dependencies, missing tree-shaking, or multi-megabyte assets).
     *
     * Baseline measurements:
     * - Entry JS (resources/js/app.tsx): ~84,679 bytes -> Budget: 95,000 bytes
     * - Entry CSS (resources/css/app.css): ~124,762 bytes -> Budget: 135,000 bytes
     * - Total JS (all chunks):
     *     - Minimal: ~450,000 bytes -> Budget: 650,000 bytes
     *     - Default: ~750,000 bytes -> Budget: 850,000 bytes
     *     - Full: ~857,421 bytes -> Budget: 950,000 bytes
     * - Total CSS: ~127,114 bytes -> Budget: 140,000 bytes
     *
     * @var array<string, array<string, int>>
     */
    private const array BUNDLE_BUDGETS = [
        Profile::MINIMAL => [
            self::METRIC_ENTRY_JS => 95_000,
            self::METRIC_ENTRY_CSS => 135_000,
            self::METRIC_TOTAL_JS => 650_000,
            self::METRIC_TOTAL_CSS => 140_000,
        ],
        Profile::STANDARD => [
            self::METRIC_ENTRY_JS => 95_000,
            self::METRIC_ENTRY_CSS => 135_000,
            self::METRIC_TOTAL_JS => 850_000,
            self::METRIC_TOTAL_CSS => 140_000,
        ],
        Profile::FULL => [
            self::METRIC_ENTRY_JS => 95_000,
            self::METRIC_ENTRY_CSS => 135_000,
            self::METRIC_TOTAL_JS => 950_000,
            self::METRIC_TOTAL_CSS => 140_000,
        ],
    ];

    public static function canonicalProfileName(string $profile): string
    {
        $normalized = mb_strtolower(mb_trim($profile));

        return match ($normalized) {
            Profile::MINIMAL => Profile::MINIMAL,
            Profile::DEFAULT, Profile::STANDARD => Profile::STANDARD,
            Profile::FULL => Profile::FULL,
            default => throw new InvalidArgumentException(sprintf(
                'Unknown profile [%s] for performance budget resolution. Available profiles: %s.',
                $profile,
                implode(', ', [Profile::MINIMAL, Profile::DEFAULT, Profile::FULL]),
            )),
        };
    }

    /**
     * @return array<string, int>
     */
    public static function queryBudgetsFor(string $profile): array
    {
        $canonical = self::canonicalProfileName($profile);

        return self::QUERY_BUDGETS[$canonical];
    }

    public static function queryBudget(string $profile, string $request): int
    {
        $budgets = self::queryBudgetsFor($profile);

        if (! array_key_exists($request, $budgets)) {
            throw new InvalidArgumentException(sprintf(
                'Unknown canonical request [%s]. Available requests: %s.',
                $request,
                implode(', ', self::CANONICAL_REQUESTS),
            ));
        }

        return $budgets[$request];
    }

    /**
     * @return array<string, int>
     */
    public static function bundleBudgetsFor(string $profile): array
    {
        $canonical = self::canonicalProfileName($profile);

        return self::BUNDLE_BUDGETS[$canonical];
    }

    public static function bundleBudget(string $profile, string $metric): int
    {
        $budgets = self::bundleBudgetsFor($profile);

        if (! array_key_exists($metric, $budgets)) {
            throw new InvalidArgumentException(sprintf(
                'Unknown bundle metric [%s]. Available metrics: %s.',
                $metric,
                implode(', ', self::BUNDLE_METRICS),
            ));
        }

        return $budgets[$metric];
    }

    /**
     * @param  list<string>  $executedQueries
     */
    public static function assertWithinQueryBudget(
        string $profile,
        string $request,
        int $actualQueries,
        array $executedQueries = [],
    ): void {
        $budget = self::queryBudget($profile, $request);

        if ($actualQueries > $budget) {
            $sqlDetails = $executedQueries !== []
                ? "\nExecuted SQL:\n  - ".implode("\n  - ", $executedQueries)
                : '';

            throw new RuntimeException(sprintf(
                'Query count regression on [%s] for profile [%s]: expected at most %d queries, got %d queries.%s',
                $request,
                $profile,
                $budget,
                $actualQueries,
                $sqlDetails,
            ));
        }
    }

    public static function assertWithinBundleBudget(
        string $profile,
        string $metric,
        int $actualBytes,
    ): void {
        $budget = self::bundleBudget($profile, $metric);

        if ($actualBytes > $budget) {
            throw new RuntimeException(sprintf(
                'Bundle size budget exceeded for [%s] in profile [%s]: expected at most %d bytes, got %d bytes (%+d bytes).',
                $metric,
                $profile,
                $budget,
                $actualBytes,
                $actualBytes - $budget,
            ));
        }
    }

    /**
     * Measure frontend production bundle sizes from Vite manifest and assets directory.
     *
     * @return array{
     *     entry_js: int,
     *     entry_css: int,
     *     total_js: int,
     *     total_css: int,
     *     chunks: array<string, int>,
     * }
     */
    public static function measureFrontendBundle(string $projectDir): array
    {
        $manifestPath = $projectDir.'/public/build/manifest.json';

        if (! file_exists($manifestPath)) {
            throw new RuntimeException(sprintf(
                'Vite manifest not found at [%s]. Ensure frontend assets have been built.',
                $manifestPath,
            ));
        }

        $manifestContent = (string) file_get_contents($manifestPath);
        /** @var array<string, array{file?: string, isEntry?: bool, css?: list<string>}>|null $manifest */
        $manifest = json_decode($manifestContent, true);

        if (! is_array($manifest)) {
            throw new RuntimeException(sprintf('Failed to parse Vite manifest at [%s].', $manifestPath));
        }

        $entryJs = null;
        $entryCss = null;
        $totalJs = 0;
        $totalCss = 0;
        $chunks = [];

        foreach ($manifest as $key => $entry) {
            $file = $entry['file'] ?? null;
            if (! is_string($file)) {
                continue;
            }

            $assetPath = $projectDir.'/public/build/'.$file;
            if (! file_exists($assetPath)) {
                continue;
            }

            $size = (int) filesize($assetPath);
            $chunks[$key] = $size;

            if ($key === 'resources/js/app.tsx') {
                $entryJs = $size;
            }

            if ($key === 'resources/css/app.css') {
                $entryCss = $size;
            }

            if (str_ends_with($file, '.js')) {
                $totalJs += $size;
            } elseif (str_ends_with($file, '.css')) {
                $totalCss += $size;
            }
        }

        throw_if($entryJs === null, RuntimeException::class, 'Entry script [resources/js/app.tsx] not found in Vite manifest.');

        throw_if($entryCss === null, RuntimeException::class, 'Entry stylesheet [resources/css/app.css] not found in Vite manifest.');

        return [
            self::METRIC_ENTRY_JS => $entryJs,
            self::METRIC_ENTRY_CSS => $entryCss,
            self::METRIC_TOTAL_JS => $totalJs,
            self::METRIC_TOTAL_CSS => $totalCss,
            'chunks' => $chunks,
        ];
    }

    /**
     * Generates a deterministic PHP script to execute inside a generated project to measure
     * canonical request query counts and return JSON-encoded results.
     */
    public static function generateHttpQueryMeasurementScript(): string
    {
        return 'require "vendor/autoload.php"; '
            .'$app = require "bootstrap/app.php"; '
            .('$kernel = $app->make('.Kernel::class.'::class); ')
            .'$kernel->bootstrap(); '
            .'config(["session.driver" => "array", "cache.default" => "array"]); '
            .'$results = []; '
            .(DB::class.'::flushQueryLog(); ')
            .(DB::class.'::enableQueryLog(); ')
            .('$welcomeRequest = '.Request::class.'::create("/", "GET"); ')
            .'$welcomeResponse = $app->handle($welcomeRequest); '
            .'$results["'.self::REQUEST_WELCOME.'"] = ['
            .'    "status" => $welcomeResponse->getStatusCode(), '
            .('    "queries" => count('.DB::class.'::getQueryLog()), ')
            .('    "sql" => array_column('.DB::class.'::getQueryLog(), "query"), ')
            .']; '
            .(DB::class.'::flushQueryLog(); ')
            .(DB::class.'::enableQueryLog(); ')
            .'$inertiaMiddlewareClass = implode("\\\\", ["App", "Http", "Middleware", "HandleInertiaRequests"]); '
            .'$inertiaMiddleware = $app->make($inertiaMiddlewareClass); '
            .('$loginReq = '.Request::class.'::create("/login", "GET"); ')
            .'$version = $inertiaMiddleware->version($loginReq); '
            .'$server = ["HTTP_X_INERTIA" => "true"]; '
            .'if ($version !== null) { $server["HTTP_X_INERTIA_VERSION"] = $version; } '
            .('$loginRequest = '.Request::class.'::create("/login", "GET", [], [], [], $server); ')
            .'$loginResponse = $app->handle($loginRequest); '
            .'$results["'.self::REQUEST_LOGIN.'"] = ['
            .'    "status" => $loginResponse->getStatusCode(), '
            .('    "queries" => count('.DB::class.'::getQueryLog()), ')
            .('    "sql" => array_column('.DB::class.'::getQueryLog(), "query"), ')
            .']; '
            .('$user = '.User::class.'::first() ?? '.User::class.'::factory()->create(); ')
            .'if ($user->email_verified_at === null) { $user->email_verified_at = now(); $user->saveQuietly(); } '
            .'auth()->setUser($user); '
            .(DB::class.'::flushQueryLog(); ')
            .(DB::class.'::enableQueryLog(); ')
            .('$dashRequest = '.Request::class.'::create("/dashboard", "GET"); ')
            .'$dashRequest->setUserResolver(fn () => $user); '
            .'$dashResponse = $app->handle($dashRequest); '
            .'$results["'.self::REQUEST_DASHBOARD.'"] = ['
            .'    "status" => $dashResponse->getStatusCode(), '
            .('    "queries" => count('.DB::class.'::getQueryLog()), ')
            .('    "sql" => array_column('.DB::class.'::getQueryLog(), "query"), ')
            .']; '
            .'echo json_encode($results);';
    }

    /**
     * @return array{
     *     schema_version: int,
     *     canonical_requests: list<string>,
     *     bundle_metrics: list<string>,
     *     profiles: array<string, array{
     *         queries: array<string, int>,
     *         bundle_bytes: array<string, int>,
     *     }>,
     * }
     */
    public static function allBaselines(): array
    {
        return [
            'schema_version' => self::SCHEMA_VERSION,
            'canonical_requests' => self::CANONICAL_REQUESTS,
            'bundle_metrics' => self::BUNDLE_METRICS,
            'profiles' => [
                Profile::MINIMAL => [
                    'queries' => self::queryBudgetsFor(Profile::MINIMAL),
                    'bundle_bytes' => self::bundleBudgetsFor(Profile::MINIMAL),
                ],
                Profile::DEFAULT => [
                    'queries' => self::queryBudgetsFor(Profile::DEFAULT),
                    'bundle_bytes' => self::bundleBudgetsFor(Profile::DEFAULT),
                ],
                Profile::FULL => [
                    'queries' => self::queryBudgetsFor(Profile::FULL),
                    'bundle_bytes' => self::bundleBudgetsFor(Profile::FULL),
                ],
            ],
        ];
    }
}
