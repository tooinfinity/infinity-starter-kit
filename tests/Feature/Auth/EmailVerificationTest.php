<?php

declare(strict_types=1);

use App\Models\User;
use Illuminate\Auth\Events\Verified;
use Illuminate\Auth\Notifications\VerifyEmail;
use Illuminate\Support\Facades\Event;
use Illuminate\Support\Facades\Notification;
use Illuminate\Support\Facades\URL;

it('redirects guests attempting to access email verification routes to login', function (): void {
    Notification::fake();

    $user = User::factory()->unverified()->create();

    $verificationUrl = (new VerifyEmail)->toMail($user)->actionUrl;

    $this->get(route('verification.notice'))
        ->assertRedirectToRoute('login');

    $this->post(route('verification.send'))
        ->assertRedirectToRoute('login');

    $this->get($verificationUrl)
        ->assertRedirectToRoute('login');

    Notification::assertNothingSent();
    expect($user->refresh()->hasVerifiedEmail())->toBeFalse();
});

it('redirects unverified users to the verification notice route', function (): void {
    $user = User::factory()->unverified()->create();

    $this->actingAs($user)
        ->get(route('dashboard'))
        ->assertRedirectToRoute('verification.notice');
});

it('renders the email verification prompt page for unverified users', function (): void {
    $user = User::factory()->unverified()->create();

    $response = $this->actingAs($user)
        ->get(route('verification.notice'));

    $response->assertOk()
        ->assertInertia(fn ($page) => $page
            ->component('user-email-verification-notification/create')
            ->has('status'));
});

it('redirects already verified users from verification notice to dashboard', function (): void {
    $user = User::factory()->create([
        'email_verified_at' => now(),
    ]);

    $response = $this->actingAs($user)
        ->get(route('verification.notice'));

    $response->assertRedirectToRoute('dashboard');
});

it('sends verification notification when unverified user requests resend', function (): void {
    Notification::fake();

    $user = User::factory()->unverified()->create();

    $response = $this->actingAs($user)
        ->fromRoute('verification.notice')
        ->post(route('verification.send'));

    $response->assertRedirectToRoute('verification.notice')
        ->assertSessionHas('status', 'verification-link-sent');

    Notification::assertSentTo($user, VerifyEmail::class);
});

it('redirects already verified users when requesting verification notification resend', function (): void {
    Notification::fake();

    $user = User::factory()->create([
        'email_verified_at' => now(),
    ]);

    $response = $this->actingAs($user)
        ->fromRoute('verification.notice')
        ->post(route('verification.send'));

    $response->assertRedirectToRoute('dashboard');

    Notification::assertNothingSent();
});

it('verifies the email through the link generated by the verification notification', function (): void {
    Event::fake();

    $user = User::factory()->unverified()->create();

    $url = (new VerifyEmail)->toMail($user)->actionUrl;

    $response = $this->actingAs($user)->get($url);

    expect($user->refresh()->hasVerifiedEmail())->toBeTrue();

    $response->assertRedirect(route('dashboard', absolute: false).'?verified=1');

    Event::assertDispatched(Verified::class, fn (Verified $event) => $event->user->is($user));
});

it('redirects to dashboard when already verified user visits verification link', function (): void {
    $user = User::factory()->create([
        'email_verified_at' => now(),
    ]);

    $verificationUrl = URL::temporarySignedRoute(
        'verification.verify',
        now()->addMinutes(60),
        ['id' => $user->getKey(), 'hash' => sha1((string) $user->email)]
    );

    $response = $this->actingAs($user)->get($verificationUrl);

    $response->assertRedirect(route('dashboard', absolute: false).'?verified=1');
});

it('requires valid signature for verification link', function (): void {
    $user = User::factory()->unverified()->create();

    $invalidUrl = route('verification.verify', [
        'id' => $user->getKey(),
        'hash' => sha1((string) $user->email),
    ]);

    $response = $this->actingAs($user)->get($invalidUrl);

    $response->assertForbidden();

    expect($user->refresh()->hasVerifiedEmail())->toBeFalse();
});

it('does not allow verification with stale hash after email changes', function (): void {
    $user = User::factory()->unverified()->create([
        'email' => 'original@example.com',
    ]);

    $url = (new VerifyEmail)->toMail($user)->actionUrl;

    $user->email = 'changed@example.com';
    $user->save();

    $response = $this->actingAs($user)->get($url);

    $response->assertForbidden();

    expect($user->refresh()->hasVerifiedEmail())->toBeFalse();
});

it('does not allow verifying email for another user', function (): void {
    $userA = User::factory()->unverified()->create();
    $userB = User::factory()->unverified()->create();

    $url = (new VerifyEmail)->toMail($userB)->actionUrl;

    $response = $this->actingAs($userA)->get($url);

    $response->assertForbidden();

    expect($userB->refresh()->hasVerifiedEmail())->toBeFalse();
});
